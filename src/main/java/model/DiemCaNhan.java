package model;

public class DiemCaNhan {
    private int diemID;
    private String maSV;
    private String hoTen;
    private String maMH;
    private String tenMonHoc;
    private int soTinChi;
    private String hocKy;
    private Double diemThuongXuyen;
    private Double diemGiuaKy;
    private Double diemCuoiKy;
    private Double diemTongKet;

    public int getDiemID() { return diemID; }
    public void setDiemID(int diemID) { this.diemID = diemID; }

    public String getMaSV() { return maSV; }
    public void setMaSV(String maSV) { this.maSV = maSV; }

    public String getHoTen() { return hoTen; }
    public void setHoTen(String hoTen) { this.hoTen = hoTen; }

    public String getMaMH() { return maMH; }
    public void setMaMH(String maMH) { this.maMH = maMH; }

    public String getTenMonHoc() { return tenMonHoc; }
    public void setTenMonHoc(String tenMonHoc) { this.tenMonHoc = tenMonHoc; }

    public int getSoTinChi() { return soTinChi; }
    public void setSoTinChi(int soTinChi) { this.soTinChi = soTinChi; }

    public String getHocKy() { return hocKy; }
    public void setHocKy(String hocKy) { this.hocKy = hocKy; }

    public Double getDiemThuongXuyen() { return diemThuongXuyen; }
    public void setDiemThuongXuyen(Double diemThuongXuyen) { this.diemThuongXuyen = diemThuongXuyen; }

    public Double getDiemGiuaKy() { return diemGiuaKy; }
    public void setDiemGiuaKy(Double diemGiuaKy) { this.diemGiuaKy = diemGiuaKy; }

    public Double getDiemCuoiKy() { return diemCuoiKy; }
    public void setDiemCuoiKy(Double diemCuoiKy) { this.diemCuoiKy = diemCuoiKy; }

    public Double getDiemTongKet() { return diemTongKet; }
    public void setDiemTongKet(Double diemTongKet) { this.diemTongKet = diemTongKet; }
}
